import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {chromium} from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({acceptDownloads:true,viewport:{width:460,height:850}});
await page.goto(process.env.CERT_BASE_URL||"http://127.0.0.1:4173/certificates/",{waitUntil:"domcontentloaded"});
await page.locator('[data-action="jobs"]').first().click();
await page.locator('[data-jc="new"]').click();
await page.locator('[data-jc-field="siteName"]').fill("JOB QA TEST - DO NOT ISSUE");
await page.locator('[data-jc-field="customer"]').fill("Local test customer");
await page.locator('[data-jc-field="email"]').fill("fixture@example.invalid");
await page.locator('[data-jc-field="address"]').fill("1 Test Street");
await page.locator('[data-jc="save"]').click();
assert.equal(await page.locator(".jc-dialog h3").first().textContent(),"JOB QA TEST - DO NOT ISSUE");
const newJobId=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificate-jobs-v1"))[0].id);
assert.match(newJobId,/^[0-9a-f-]{36}$/);
await page.locator('[data-jc="qr"]').click();
assert(await page.locator(".jc-qr").count()>0,"QR label missing");
assert(await page.locator(".jc-qr canvas,.jc-qr img").count()>0,"QR code not generated offline");
await page.locator('[data-jc="hideqr"]').click();
await page.locator('[data-jc-date]').fill("2026-10-30");
await page.locator('[data-jc-describe]').fill("Explicit inspection due - TEST ONLY");
await page.locator('[data-jc="reminder-add"]').click();
assert((await page.locator(".jc-dialog").textContent()).includes("Explicit inspection due - TEST ONLY"));
await page.locator('[data-jc="close"]').click();
await page.locator('#speed-nav [data-speed="new"]').click();
await page.locator('.cert-launch[data-type="eic"]').click();
await page.locator('[data-action="jobs"]').first().click();
await page.locator('[data-jc="open"][data-id="'+newJobId+'"]').first().click();
await page.locator('[data-jc-cert]').selectOption({index:1});
await page.locator('[data-jc="link"]').click();
const certLinked=await page.evaluate(()=>{
 const cert=JSON.parse(localStorage.getItem("sperin-certificates-data-v1"));
 return cert.certificates?.some(c=>c.jobId);
});
assert(certLinked,"Certificate was not linked to job locally");
const png=Buffer.from((await page.evaluate(()=>{const c=document.createElement("canvas");c.width=8;c.height=8;c.getContext("2d").fillRect(0,0,8,8);return c.toDataURL("image/png");})).split(",")[1],"base64");
await page.locator('[data-jc-file]').setInputFiles({name:"fuseboard-fixture.png",mimeType:"image/png",buffer:png});
await page.locator('[data-jc-circuit]').fill("DB1 / 1");
await page.locator('[data-jc-observation]').fill("OBS-1");
await page.locator('[data-jc-label]').fill("Device marking evidence");
await page.locator('[data-jc="photo-add"]').click();
await page.waitForFunction(()=>document.querySelector(".jc-dialog")?.textContent?.includes("Device marking evidence"),null,{timeout:8000}).catch(()=>{});
assert((await page.locator(".jc-dialog").textContent()).includes("Device marking evidence"),"Evidence did not appear: "+(await page.locator("[data-jc-status]").textContent()));
const [download]=await Promise.all([
 page.waitForEvent("download",{timeout:16000}),
 page.locator('[data-jc="pack"]').click()
]);
const file="/tmp/sperin-job-handover-QA.zip";await download.saveAs(file);
const bytes=await fs.readFile(file);assert.equal(bytes.subarray(0,4).toString("hex"),"504b0304");
assert(bytes.includes(Buffer.from("certificates/")),"Missing certificate PDF in ZIP");
assert(bytes.includes(Buffer.from("evidence/")),"Missing evidence image in ZIP");
const dataBefore=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificate-jobs-v1")));
assert.equal(dataBefore.length,1);
await page.reload();
await page.locator('[data-action="jobs"]').first().click();
if(await page.locator('[data-jc="open"][data-id="'+newJobId+'"]').count())await page.locator('[data-jc="open"][data-id="'+newJobId+'"]').first().click();
assert((await page.locator(".jc-dialog").textContent()).includes("Device marking evidence"),"Offline job persistence failed");
await page.locator('[data-jc="sync"]').click();
assert((await page.locator("[data-jc-status]").textContent()).includes("Enable cloud consent"),"Cloud upload must remain disabled by default");
await browser.close();
console.log("JOBS_QR_EVIDENCE_REMINDERS_PDF_HANDOVER_ZIP_AND_OPT_IN_PASS");
