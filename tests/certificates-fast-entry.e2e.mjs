import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {chromium} from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:375,height:750},acceptDownloads:true});
page.on("pageerror",e=>{console.log("PAGE_ERROR",e.message);});
await page.goto(process.env.CERT_BASE_URL||"http://127.0.0.1:4173/certificates/",{waitUntil:"domcontentloaded"});
await page.locator("#speed-nav").waitFor({timeout:5000});
assert.equal(await page.locator(".speed-links [data-speed]").count(),5,"Five tap navigation");
assert.equal(await page.locator(".cert-launch").count(),9,"All certificate types preserved");
await page.locator('[data-speed="theme"]').click();
assert.equal(await page.locator("html").getAttribute("data-theme"),"dark");
await page.reload();
await page.locator("#speed-nav").waitFor();
assert.equal(await page.locator("html").getAttribute("data-theme"),"dark","Dark mode persists");
await page.locator('[data-speed="theme"]').click();
await page.locator('.cert-launch[data-type="eicr"]').click();
const firstId=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificates-data-v1")).certificates[0].id);
await page.locator('[data-action="speed-quick"]').first().click();
await page.locator('[data-preset="0"]').click();
await page.locator('[data-preset="1"]').click();
const initial=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificates-data-v1")).certificates[0]);
assert.equal(initial.tables.circuits.filter(c=>c.description==="Socket outlets").length,1);
assert.equal(initial.tables.circuits.filter(c=>c.description==="Lighting").length,1);
assert.equal(initial.tables.tests.find(t=>String(t.circuitNo)===String(initial.tables.circuits.find(c=>c.description==="Socket outlets").circuitNo)).zs||"","","Quick presets must never populate measured Zs");
await page.locator("[data-speed-close]").click();
await page.locator('[data-action="speed-bulk"]').first().click();
await page.locator("[data-schedule]").selectOption("circuits");
await page.locator("[data-column]").selectOption("description");
await page.locator("[data-find]").fill("Socket outlets");
await page.locator("[data-replace]").fill("Ring final sockets");
await page.locator("[data-preview]").click();
assert.equal(await page.locator("[data-pick]:checked").count(),1);
page.once("dialog",d=>d.accept());
await page.locator("[data-apply]").click();
const changed=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificates-data-v1")).certificates[0]);
assert(changed.tables.circuits.some(c=>c.description==="Ring final sockets"));
assert(!changed.tables.tests.some(t=>t.zs),"No tests changed during text replacement");
await page.locator('[data-action="speed-convert"]').first().click();
await page.locator("[data-type]").selectOption("eic");
page.once("dialog",d=>d.accept());
await page.locator("[data-create]").click();
const certs=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificates-data-v1")).certificates);
assert.equal(certs.length,2);
assert.equal(certs[0].type,"eic");
assert.equal(certs[0].status,"Draft");
assert.equal(certs[0].sourceCertificateId,firstId);
assert(certs[0].tables.circuits.some(c=>c.description==="Ring final sockets"));
assert(certs[0].tables.tests.every(t=>!t.zs&&!t.irLL&&!t.rcdTime));
assert.equal(certs[0].fields.inspectorSignature,"");
assert.equal(certs[1].type,"eicr","Original EICR retained");
await page.locator('[data-speed="more"]').click();
await page.locator('[data-tool="bluetooth"]').click();
assert((await page.locator(".speed-dialog").textContent()).includes("Megger"));
await page.locator("[data-speed-close]").click();
await page.locator('[data-action="settings"]').first().click();
await page.locator('[data-setting="reportAccent"]').fill("#a23ac1");
await page.locator('[data-action="save-settings"]').click();
const settings=await page.evaluate(()=>JSON.parse(localStorage.getItem("sperin-certificates-settings-v1")||"{}"));
assert(!settings.reportAccent||/^#[0-9a-f]{6}$/i.test(settings.reportAccent));
const [pdf]=await Promise.all([page.waitForEvent("download",{timeout:20000}),page.locator('[data-action="pdf"]').first().click()]);
assert(pdf.suggestedFilename().endsWith(".pdf"));
await pdf.saveAs("/tmp/sperin-speed-branded-eic.pdf");
const buf=await fs.readFile("/tmp/sperin-speed-branded-eic.pdf");
assert.equal(buf.subarray(0,5).toString(),"%PDF-");
await browser.close();
console.log("SPEED_UX_DARK_PRESETS_BULK_SAFE_CONVERSION_BLUETOOTH_PDF_PASS");
