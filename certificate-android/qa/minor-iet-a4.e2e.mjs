import { chromium } from "playwright";
import fs from "node:fs";
import assert from "node:assert/strict";

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:412,height:915},acceptDownloads:true});
const errors=[];
page.on("pageerror",e=>errors.push(String(e)));
page.on("dialog",dlg=>dlg.accept());
await page.goto(process.env.CERT_BASE_URL||"http://127.0.0.1:4173/certificates/");
await page.locator('[data-action="new"][data-type="minor"]').click();
const fill=async(key,value)=>{
 const el=page.locator('[data-field="'+key+'"]');
 assert.equal(await el.count(),1,key+" missing");
 await el.evaluate(input=>{
   for(let d=input.closest('details[data-accordion-key]');d;d=d.parentElement?.closest('details[data-accordion-key]'))d.open=true;
 });
 await el.fill(value);
 await el.dispatchEvent("change");
};
await fill("clientName","Minor Works Client QA");
await fill("installationAddress","25 Electric Way, Testtown");
await fill("description","Addition of one socket on existing circuit");
await fill("dbReference","DB2");
await fill("circuitNo","3");
await fill("circuitDescription","Existing socket ring");
await fill("ocpdBs","BS EN 61009-1");
await fill("ocpdType","B");
await fill("ocpdRating","32");
await fill("rcdBs","BS EN 61009-1");
await fill("rcdType","A");
await fill("rcdRating","32");
await fill("rcdIdn","30");
await fill("rcdDelay","0");
await fill("spdBs","BS EN IEC 61643-11");
await fill("spdType","T2");
await fill("afddBs","BS EN 62606");
await fill("afddRating","16");
await fill("engineerName","Minor Works Electrician QA");
await fill("signature","ELECTRICIAN QA SIGNED");
await fill("position","Electrician");
await fill("declarationDate","2026-10-21");
const [download]=await Promise.all([page.waitForEvent("download"),page.locator('[data-action="pdf"]').first().click()]);
fs.mkdirSync("certificate-android/qa-output",{recursive:true});
await download.saveAs("certificate-android/qa-output/minor-iet-a4.pdf");
assert.ok(fs.statSync("certificate-android/qa-output/minor-iet-a4.pdf").size>10000);
assert.deepEqual(errors,[]);
await browser.close();
console.log("MINOR_WORKS_IET_A4_PDF_SAVE_PASS");
